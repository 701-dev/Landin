# --------------------------------------------------------------------- main

def render_all():
    return {FIXTURES / "core-text-parse-radix-oracle" / "main.ldn":
            radix_fixture(),
            FIXTURES / "core-text-quoted" / "main.ldn": quoted_fixture()}


def main(arguments=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args(arguments)
    stale = []
    for path, text in sorted(render_all().items()):
        if options.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    for path in stale:
        print("text_fixtures.py: %s is not what the generator writes; run"
              " scripts/text_fixtures.py" % path.relative_to(ROOT),
              file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
