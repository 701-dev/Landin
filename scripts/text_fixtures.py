# ----------------------------------------------------------- the quoted form

#  The scalars `append_quoted` writes as `\u{...}`: the controls, and those
#  that change how the text around them reads without being seen.
UNSEEN = ({0x061C, 0x200E, 0x200F, 0xFEFF} | set(range(0x2028, 0x202F))
          | set(range(0x2066, 0x206A)))
NAMED = {0x0A: "\\n", 0x0D: "\\r", 0x09: "\\t", 0x1B: "\\e",
         0x5C: "\\\\", 0x22: "\\\""}


def quoted(text):
    """TEXT as append_quoted writes it, the quotes included."""
    out = '"'
    for character in text:
        scalar = ord(character)
        if scalar in NAMED:
            out += NAMED[scalar]
        elif scalar < 0x20 or 0x7F <= scalar < 0xA0 or scalar in UNSEEN:
            out += "\\u{%x}" % scalar
        else:
            out += character
    return out + '"'


def spelled(text):
    """TEXT as a literal of this script's own, every scalar outside the
    printable ASCII range escaped, so that it does not depend on the form
    under test."""
    out = '"'
    for character in text:
        scalar = ord(character)
        if character in '"\\':
            out += "\\" + character
        elif 0x20 <= scalar < 0x7F:
            out += character
        else:
            out += "\\u{%x}" % scalar
    return out + '"'


def quoted_cases():
    cases = ["", "plain", "a\"b\\c'd", "\n\r\t\x1b", "tab\there"]
    cases += [chr(scalar) for scalar in range(0x00, 0x20)]
    cases += [chr(scalar) for scalar in range(0x7F, 0xA1)]
    cases += [chr(scalar) for scalar in sorted(UNSEEN)]
    cases += ["é", "€", "\U0001f600", " ", "́",
              "​", "‧", " ", "⁥", "⁪",
              "\U0010ffff", "", "�", "﻾",
              "é א‮ב⁩ \U0001f469‍\U0001f4bb",
              "{}${x}\\u{41}"]
    return cases


