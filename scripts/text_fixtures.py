GENERATED = "--  Generated by scripts/text_fixtures.py; do not edit it."

OFFSET = 0x811C9DC5
PRIME = 0x01000193
MASK = (1 << 32) - 1
DIGITS = "0123456789abcdefghijklmnopqrstuvwxyz"


def fnv(state, data):
    for byte in data:
        state = ((state ^ byte) * PRIME) & MASK
    return state


# ------------------------------------------------------------ radix parsing

#  Each width the oracle parses: its name, whether it is signed, its bits.
WIDTHS = (("u8", False, 8), ("u16", False, 16), ("u32", False, 32),
          ("u64", False, 64), ("i8", True, 8), ("i16", True, 16),
          ("i32", True, 32), ("i64", True, 64))

#  Magnitudes at the widths' edges, and two between them.
MAGNITUDES = (0, 1, 9, 0x7F, 0x80, 0xFF, 0x100, 0x7FFF, 0x8000, 0xFFFF,
              0x10000, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0x100000000,
              0x7FFFFFFFFFFFFFFF, 0x8000000000000000, 0xFFFFFFFFFFFFFFFF,
              0x123456789ABCDEF0, 1234567)

#  The prefix that names a radix.
PREFIXES = {16: "x", 8: "o", 2: "b"}

#  Every how many radixes firmware parses.
RADIX_STRIDE = 7

#  A parse's outcome: a value, `invalid_number` or `number_overflow`.
VALUE, INVALID, OVERFLOW = 0, 1, 2


def written(magnitude, radix):
    """MAGNITUDE's digits in RADIX, lower case."""
    if magnitude == 0:
        return "0"
    digits = ""
    while magnitude:
        digits = DIGITS[magnitude % radix] + digits
        magnitude //= radix
    return digits


def texts(radix, signed):
    """Each text the oracle parses in RADIX, in the program's order."""
    mark = PREFIXES.get(radix, "x")
    bad = DIGITS[radix] if radix < 36 else "_"
    for magnitude in MAGNITUDES:
        digits = written(magnitude, radix)
        for sign in (("", "-") if signed else ("",)):
            for prefix in ("", "0" + mark, "0" + mark.upper()):
                for suffix in ("", "0", bad):
                    yield sign + prefix + digits + suffix


def outcome(text, radix, signed, bits):
    """What parsing TEXT in RADIX at a width gives, as Python reads it."""
    negative = text.startswith("-")
    if negative and not signed:
        return INVALID, 0
    body = text[1:] if negative else text
    if body[:2].lower() == "0" + PREFIXES.get(radix, "\0"):
        body = body[2:]
    if not body:
        return INVALID, 0
    if signed:
        limit = (1 << (bits - 1)) if negative else (1 << (bits - 1)) - 1
    else:
        limit = (1 << bits) - 1
    #  The scan reads from the left: whichever of an invalid digit and an
    #  overflow it meets first is the refusal.
    bad = len(body)
    for index, character in enumerate(body):
        if character.lower() not in DIGITS[:radix]:
            bad = index
            break
    for ends in range(1, bad + 1):
        if int(body[:ends], radix) > limit:
            return OVERFLOW, 0
    if bad < len(body):
        return INVALID, 0
    value = int(body, radix)
    if negative:
        value = -value
    return VALUE, value & ((1 << 64) - 1)


def radix_digest(stride):
    state = OFFSET
    for _, signed, bits in WIDTHS:
        for radix in range(2, 37, stride):
            for text in texts(radix, signed):
                code, value = outcome(text, radix, signed, bits)
                state = fnv(state, [code])
                state = fnv(state, value.to_bytes(8, "little"))
    return state


