"""The `unicode-*` runtime fixtures scripts/unicode_tables.py writes.

Each fixture's program is its oracle's, computed here from the Unicode
Character Database and its conformance files, never from core/unicode's
tables, and exits 42 only when core/unicode agrees with every value.

A walk fixture goes through the scalars from zero to U+10FFFF and feeds
what core/unicode answers for each into FNV-1a, 32 bits, which must end at
the digest written here from the database's own files.  A hosted target
walks every scalar.  Firmware walks every STRIDE-th one, under
`fixed if compiler.os == freestanding`, to its own digest: the Cortex-M
corpus gives each run 20 seconds of an emulator, which a walk of every
scalar outlasts, and every target reads the same tables, so what a
firmware target checks is its own code over them.

- `unicode-category` and `unicode-properties`: the general category, and
  the combining class and binary properties, of every value.
- `unicode-case-scalars`: each scalar's simple and full case mappings, the
  full ones of the scalar as a text of its own; `unicode-case-title` its
  title case as such a text, which needs the word tables too.
- `unicode-normalization-canonical` and `-compatible`: each scalar's forms,
  as NormalizationTest.txt's part 1 and its rule for an unlisted scalar
  say, and each form of each form as the file's invariants require.
- `unicode-normalization-sequences`: every other line of the file, its
  source column held and the other four by their digest.
- `unicode-graphemes`, `-words-N` and `-sentences`: every line of their
  conformance file, its text and its boundaries, checked through both
  core/unicode's boundary routine and its `for` walk, split into parts
  that each fit Cortex-M0's 32 KiB of flash.
"""

import unicode_tables as tables

OFFSET = 0x811C9DC5
PRIME = 0x01000193
MASK = (1 << 32) - 1


def fnv(state, data):
    for byte in data:
        state = ((state ^ byte) * PRIME) & MASK
    return state


def walk(stride, skip_surrogates):
    """The scalars a walk fixture's loop visits, in its order."""
    scalar = 0
    while scalar <= 0x10FFFF:
        if skip_surrogates and 0xD800 <= scalar <= 0xDFFF:
            scalar = 0xE000
        yield scalar
        scalar += stride


def header(summary):
    return [
        "--  Generated by scripts/unicode_tables.py from the Unicode"
        " Character",
        "--  Database %s; do not edit it.  %s" % (tables.VERSION, summary[0]),
    ] + ["--  " + line for line in summary[1:]]


def text_lines(text):
    return text.strip("\n").split("\n")


FEED = text_lines("""
--  FNV-1a, 32 bits: fold one byte into the digest.
feed: (inout state: u32, value: u8) -> none =
    state = (state ^ u32(value)) *% 0x01000193
end feed
""")

FEED_TEXT = text_lines("""
--  Fold the bytes of `value` into the digest, then a byte no UTF-8 holds.
feed_text: (inout state: u32, value: utf8) -> none =
    for each in text.bytes(value) do
        feed(state, each)
    end for
    feed(state, 0xff)
end feed_text
""")

FEED_SCALAR = text_lines("""
--  Fold the four bytes of `value`, the lowest first, into the digest.
feed_scalar: (inout state: u32, value: u32) -> none =
    feed(state, u8(value & 0xff))
    feed(state, u8((value >> 8) & 0xff))
    feed(state, u8((value >> 16) & 0xff))
    feed(state, u8(value >> 24))
end feed_scalar
""")

ENCODE = text_lines("""
--  The text of `scalar` alone, encoded over `storage`.
alone: (scalar: u32, storage: []mut u8) -> (result: utf8 from storage) =
    count: usize = text.encode(scalar, storage) else begin
        compiler.unreachable()
    end
    result = text.from_bytes(storage[0..<count]) else begin
        compiler.unreachable()
    end
end alone
""")


def ordinal(number):
    if number % 100 in (11, 12, 13):
        return "%dth" % number
    return "%d%s" % (number, {1: "st", 2: "nd", 3: "rd"}.get(number % 10,
                                                            "th"))


def walk_fixture(summary, imports, helpers, body, digest, stride,
                 skip_surrogates, buffers=()):
    """A walk fixture: DIGEST(scalars) is the oracle's digest.

    BODY is the loop body's lines at two levels of indentation, which
    feeds `state` for `scalar` or leaves `main` with its code of one.
    STRIDE is firmware's, or None for a fixture firmware does not run.
    BUFFERS are `main`'s locals the body writes into.
    """
    every = digest(walk(1, skip_surrogates))
    lines = header(summary) + [""] + ["import %s" % name for name in imports]
    lines.append("")
    if stride is None:
        lines += ["stride: u32 = 1", "expected: u32 = 0x%08x" % every]
    else:
        sampled = digest(walk(stride, skip_surrogates))
        lines += [
            "--  Firmware walks every %s scalar, within the emulator's"
            % ordinal(stride),
            "--  session; a hosted target walks them all.",
            "fixed if compiler.os == freestanding then",
            "    stride: u32 = %d" % stride,
            "    expected: u32 = 0x%08x" % sampled,
            "else",
            "    stride: u32 = 1",
            "    expected: u32 = 0x%08x" % every,
            "end if",
        ]
    lines += [""] + FEED + [""]
    for helper in helpers:
        lines += helper + [""]
    lines += ["public main: () -> (code: i32) =",
              "    code = 1",
              "    mut state: u32 = 0x811c9dc5"]
    lines += ["    mut %s: [%d]u8 = zeroed" % buffer for buffer in buffers]
    lines += ["    mut scalar: u32 = 0",
              "    while scalar <= 0x10ffff do"]
    if skip_surrogates:
        lines += ["        if scalar >= 0xd800 and scalar <= 0xdfff then",
                  "            scalar = 0xe000",
                  "        end if"]
    lines += body
    lines += ["        scalar += stride",
              "    end while",
              "    if state == expected then",
              "        code = 42",
              "    end if",
              "end main"]
    return lines


def category_fixture(database):
    def digest(scalars):
        state = OFFSET
        for scalar in scalars:
            state = fnv(state, [database.category[scalar]])
        return state
    arms = ["        unicode.%s: value = %d" % (atom, code)
            for code, (_, atom) in enumerate(tables.CATEGORIES)]
    code_of = (["--  A category's place in the database's order.",
                "code_of: (kind: unicode.general_category) -> (value: u8) ="]
               + ["    match kind"] + arms + ["    end match", "end code_of"])
    return walk_fixture(
        ["Every value from zero", "to U+10FFFF has the general category"
         " the database gives it: the", "digest of each one's code, its"
         " place in the database's order, is", "the database's."],
        ["core/unicode"], [code_of],
        ["        feed(state, code_of(unicode.category(scalar)))"],
        digest, 7, False)


def properties_fixture(database):
    def digest(scalars):
        state = OFFSET
        for scalar in scalars:
            state = fnv(state, [database.combining[scalar],
                                database.flags[scalar]])
        return state
    bits = text_lines("""
--  The six binary properties, one bit each, Alphabetic the lowest.
bits_of: (scalar: u32) -> (value: u8) =
    value = 0
    if unicode.is_alphabetic(scalar) then
        value |= 1
    end if
    if unicode.is_white_space(scalar) then
        value |= 2
    end if
    if unicode.is_uppercase(scalar) then
        value |= 4
    end if
    if unicode.is_lowercase(scalar) then
        value |= 8
    end if
    if unicode.is_cased(scalar) then
        value |= 16
    end if
    if unicode.is_case_ignorable(scalar) then
        value |= 32
    end if
end bits_of
""")
    return walk_fixture(
        ["Every value from zero", "to U+10FFFF has the canonical combining"
         " class and the binary", "properties the database gives it: the"
         " digest of the class and of", "the properties' bits, Alphabetic"
         " the lowest, is the database's."],
        ["core/unicode"], [bits],
        ["        feed(state, unicode.combining_class(scalar))",
         "        feed(state, bits_of(scalar))"],
        digest, 13, False)


def little(value):
    return [(value >> shift) & 255 for shift in (0, 8, 16, 24)]


CASE_KINDS = ("upper", "lower", "title", "fold")


def case_fixture(database):
    def digest(scalars):
        state = OFFSET
        for scalar in scalars:
            for kind in CASE_KINDS:
                state = fnv(state, little(database.simple(kind, scalar)))
            for kind in ("upper", "lower", "fold"):
                state = fnv(state, tables.encoded(
                    database.full(kind, scalar)) + b"\xff")
        return state
    body = text_lines("""
        feed_scalar(state, unicode.simple_upper(scalar))
        feed_scalar(state, unicode.simple_lower(scalar))
        feed_scalar(state, unicode.simple_title(scalar))
        feed_scalar(state, unicode.simple_fold(scalar))
        source: utf8 = alone(scalar, encoded)
        mut into: text.utf8_builder = text.utf8_over(storage)
        unicode.append_upper(into, source) else begin return end
        feed_text(state, text.utf8_used(into))
        text.utf8_clear(into)
        unicode.append_lower(into, source) else begin return end
        feed_text(state, text.utf8_used(into))
        text.utf8_clear(into)
        unicode.append_folded(into, source) else begin return end
        feed_text(state, text.utf8_used(into))
""")
    return walk_fixture(
        ["Every scalar has the", "simple and full case mappings the"
         " database gives it: the digest of", "its simple upper, lower,"
         " title and folded mappings, each four bytes", "with the lowest"
         " first, and then of its full upper, lower and folded", "ones,"
         " each of the scalar as a text of its own, is the database's.",
         "A lone capital sigma is no word's final sigma."],
        ["core/text", "core/unicode"], [FEED_TEXT, FEED_SCALAR, ENCODE],
        body, digest, 31, True, (("encoded", 4), ("storage", 64)))


def title_fixture(database):
    def digest(scalars):
        state = OFFSET
        for scalar in scalars:
            if database.flags[scalar] & 16:
                full = database.full("title", scalar)
            else:
                full = [scalar]
            state = fnv(state, tables.encoded(full) + b"\xff")
        return state
    body = text_lines("""
        source: utf8 = alone(scalar, encoded)
        mut into: text.utf8_builder = text.utf8_over(storage)
        unicode.append_title(into, source) else begin return end
        feed_text(state, text.utf8_used(into))
""")
    return walk_fixture(
        ["Every scalar, as a", "text of its own, has the title case the"
         " database gives it: a text of", "one scalar is one word, so its"
         " title case is its full title mapping", "when it is cased and"
         " itself when it is not, and the digest of those", "is the"
         " database's."],
        ["core/text", "core/unicode"], [FEED_TEXT, ENCODE], body, digest,
        31, True, (("encoded", 4), ("storage", 64)))


def normalization_lines(database):
    """NormalizationTest.txt's lines: (part, [five columns of scalars])."""
    part = None
    for line in database.members["NormalizationTest.txt"].splitlines():
        if line.startswith("@Part"):
            part = int(line[5])
            continue
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        columns = [tables.scalars(column) for column in line.split(";")[:5]]
        yield part, columns


FORMS = {"canonical": ("nfc", "nfd"), "compatible": ("nfkc", "nfkd")}
PICKS = {"nfc": 1, "nfd": 2, "nfkc": 3, "nfkd": 4}


def form_helpers(forms):
    first, second = forms
    return [text_lines("""
--  Form `form` of `source`, %(upper_first)s or %(upper_second)s from zero,
--  written over `storage`.
form_of: (form: u8, source: utf8, storage: []mut u8)
         -> (result: utf8 from storage) ! mem.out_of_memory =
    mut into: text.utf8_builder = text.utf8_over(storage)
    if form == 0 then
        try unicode.append_%(first)s(into, source)
    else
        try unicode.append_%(second)s(into, source)
    end if
    result = text.utf8_used(into)
end form_of
""" % {"first": first, "second": second, "upper_first": first.upper(),
       "upper_second": second.upper()}), text_lines("""
--  Whether form `form` of `source` is `wanted`.
gives: (form: u8, source: utf8, wanted: utf8, storage: []mut u8)
       -> (yes: bool) =
    found: utf8 = form_of(form, source, storage) else begin
        yes = false
        return
    end
    yes = text.equal(found, wanted)
end gives
""")]


def scalar_normalization_fixture(database, which, stride):
    listed = {}
    for part, columns in normalization_lines(database):
        if part == 1:
            listed[columns[0][0]] = columns
    forms = FORMS[which]

    def digest(scalars):
        state = OFFSET
        for scalar in scalars:
            columns = listed.get(scalar, [[scalar]] * 5)
            for form in forms:
                state = fnv(state, tables.encoded(columns[PICKS[form]])
                            + b"\xff")
        return state
    #  The invariants among the two columns this fixture computes: the
    #  composed one is the composition of both, the decomposed one the
    #  decomposition of both.
    body = text_lines("""
        source: utf8 = alone(scalar, encoded)
        once: utf8 = form_of(0, source, composed) else begin return end
        apart: utf8 = form_of(1, source, decomposed) else begin return end
        feed_text(state, once)
        feed_text(state, apart)
        if not text.equal(once, source) or not text.equal(apart, source)
        then
            return when not gives(0, once, once, again)
            return when not gives(0, apart, once, again)
            return when not gives(1, once, apart, again)
            return when not gives(1, apart, apart, again)
        end if
""")
    upper = tuple(form.upper() for form in forms)
    return walk_fixture(
        ["Every scalar, as a", "text of its own, has the %s and %s forms"
         " NormalizationTest.txt's" % upper, "part 1 gives it, and a scalar"
         " the part does not list is its own", "form, as the file's second"
         " invariant says: the digest of the", "forms is the file's.  Each"
         " form of a form is what the file's", "first invariants require of"
         " its columns."],
        ["core/mem", "core/text", "core/unicode"],
        [FEED_TEXT, ENCODE] + form_helpers(forms), body, digest, stride,
        True, (("encoded", 4), ("composed", 96), ("decomposed", 96),
               ("again", 96)))


def byte_array(name, data):
    return tables.array(name, "u8", list(data))


#  Every how many lines of NormalizationTest.txt firmware checks.
SEQUENCE_STRIDE = 7


def sequences_fixture(database):
    data = bytearray()
    ends = []
    lines_held = []
    longest = 0
    for part, columns in normalization_lines(database):
        if part == 1:
            continue
        data += tables.encoded(columns[0])
        ends.append(len(data))
        lines_held.append(columns)
        for column in columns[1:]:
            longest = max(longest, len(tables.encoded(column)))
    if longest > 256:
        raise tables.GeneratorError("a column of %d bytes" % longest)

    def digest(stride):
        state = OFFSET
        for columns in lines_held[::stride]:
            for column in columns[1:]:
                state = fnv(state, tables.encoded(column) + b"\xff")
        return state
    lines = header([
        "Each line of",
        "NormalizationTest.txt but part 1's meets every invariant the file",
        "states.  The fixture holds each line's source, c1, and the digest",
        "of the other four columns, which are its NFC, NFD, NFKC and NFKD",
        "forms: the digest of the forms core/unicode gives is the file's,",
        "and of those forms c2 is the NFC of c2 and c3, and c4 that of c4",
        "and c5; c3 is the NFD of c2 and c3, and c5 that of c4 and c5; c4 is",
        "the NFKC and c5 the NFKD of every column."])
    lines += ["", "import core/mem", "import core/text", "import core/unicode",
              "",
              "--  Firmware checks every %s line, within the emulator's"
              % ordinal(SEQUENCE_STRIDE),
              "--  session; a hosted target checks them all.",
              "fixed if compiler.os == freestanding then",
              "    stride: usize = %d" % SEQUENCE_STRIDE,
              "    expected: u32 = 0x%08x" % digest(SEQUENCE_STRIDE),
              "else",
              "    stride: usize = 1",
              "    expected: u32 = 0x%08x" % digest(1),
              "end if", ""]
    lines += byte_array("sources", data)
    lines += tables.array("ends", "u32", ends)
    lines += [""] + FEED + [""] + FEED_TEXT
    lines += text_lines("""
--  The source column of line `line`.
source_of: (line: usize) -> (value: utf8) =
    begins: usize = if line == 0 then 0 else usize(ends[line - 1]) end if
    unchecked begin
        value = compiler.utf8_unvalidated(sources[begins..<usize(ends[line])])
    end unchecked
end source_of

--  Form `form` of `source`, NFC, NFD, NFKC or NFKD from zero, written
--  over `storage`.
form_of: (form: u8, source: utf8, storage: []mut u8)
         -> (result: utf8 from storage) ! mem.out_of_memory =
    mut into: text.utf8_builder = text.utf8_over(storage)
    if form == 0 then
        try unicode.append_nfc(into, source)
    elsif form == 1 then
        try unicode.append_nfd(into, source)
    elsif form == 2 then
        try unicode.append_nfkc(into, source)
    else
        try unicode.append_nfkd(into, source)
    end if
    result = text.utf8_used(into)
end form_of

--  Whether form `form` of `source` is `wanted`.
gives: (form: u8, source: utf8, wanted: utf8, storage: []mut u8)
       -> (yes: bool) =
    found: utf8 = form_of(form, source, storage) else begin
        yes = false
        return
    end
    yes = text.equal(found, wanted)
end gives

public main: () -> (code: i32) =
    code = 1
    mut state: u32 = 0x811c9dc5
    mut c2_storage: [256]u8 = zeroed
    mut c3_storage: [256]u8 = zeroed
    mut c4_storage: [256]u8 = zeroed
    mut c5_storage: [256]u8 = zeroed
    mut again: [256]u8 = zeroed
    mut line: usize = 0
    while line < lenof ends do
        c1: utf8 = source_of(line)
        c2: utf8 = form_of(0, c1, c2_storage) else begin return end
        c3: utf8 = form_of(1, c1, c3_storage) else begin return end
        c4: utf8 = form_of(2, c1, c4_storage) else begin return end
        c5: utf8 = form_of(3, c1, c5_storage) else begin return end
        feed_text(state, c2)
        feed_text(state, c3)
        feed_text(state, c4)
        feed_text(state, c5)
        return when not gives(0, c2, c2, again) or not gives(0, c3, c2, again)
        return when not gives(0, c4, c4, again) or not gives(0, c5, c4, again)
        return when not gives(1, c2, c3, again) or not gives(1, c3, c3, again)
        return when not gives(1, c4, c5, again) or not gives(1, c5, c5, again)
        return when not gives(2, c2, c4, again) or not gives(2, c3, c4, again)
        return when not gives(2, c4, c4, again) or not gives(2, c5, c4, again)
        return when not gives(3, c2, c5, again) or not gives(3, c3, c5, again)
        return when not gives(3, c4, c5, again) or not gives(3, c5, c5, again)
        line += stride
    end while
    if state == expected then
        code = 42
    end if
end main
""")
    return lines


def break_cases(text):
    """Each line's scalars and the byte offsets of its inner boundaries."""
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        tokens = line.split()
        scalars, boundaries, offset = [], [], 0
        for token in tokens[1:-1]:
            if token == "÷":
                boundaries.append(offset)
            elif token != "×":
                scalar = int(token, 16)
                scalars.append(scalar)
                offset += len(chr(scalar).encode("utf-8"))
        if tokens[0] != "÷" or tokens[-1] != "÷":
            raise tables.GeneratorError("a break line without its ends")
        boundaries.append(offset)
        yield scalars, boundaries


#  The bytes of conformance data one break fixture holds at most, so that
#  with its unit's table and code it fits Cortex-M0's 32 KiB of flash.
BREAK_DATA = 16000


def break_parts(cases):
    """CASES split into parts of at most BREAK_DATA bytes of data each."""
    parts, part, size = [], [], 0
    for scalars, found in cases:
        cost = len(tables.encoded(scalars)) + 4 + 2 * len(found)
        if part and size + cost > BREAK_DATA:
            parts.append(part)
            part, size = [], 0
        part.append((scalars, found))
        size += cost
    parts.append(part)
    return parts


def break_fixture(member, unit, plural, cases, part, parts):
    data = bytearray()
    ends = []
    boundaries = []
    counts = []
    for scalars, found in cases:
        data += tables.encoded(scalars)
        ends.append(len(data))
        boundaries.extend(found)
        counts.append(len(boundaries))
    which = ("Each line of" if parts == 1 else
             "Each line of part %d of %d of" % (part, parts))
    lines = header([
        which,
        "%s has the %s boundaries the file gives it: each" % (
            member.split("/")[-1], unit),
        "`unicode.%s_end` from the line's start, and each segment" % unit,
        "`unicode.%s` walks, ends at the next of them." % plural])
    lines += ["", "import core/text", "import core/unicode", ""]
    lines += byte_array("cases", data)
    lines += tables.array("ends", "u16", ends)
    lines += tables.array("boundaries", "u16", boundaries)
    lines += tables.array("counts", "u16", counts)
    lines += ("""
--  The text of case `index`.
case_of: (index: usize) -> (value: utf8) =
    begins: usize = if index == 0 then 0 else usize(ends[index - 1]) end if
    unchecked begin
        value = compiler.utf8_unvalidated(cases[begins..<usize(ends[index])])
    end unchecked
end case_of

--  Whether the boundaries of case `index` are the file's, both ways.
holds: (index: usize) -> (yes: bool) =
    yes = false
    source: utf8 = case_of(index)
    first: usize = if index == 0 then 0 else usize(counts[index - 1]) end if
    last: usize = usize(counts[index])
    mut at: text.position = text.start(source)
    mut next: usize = first
    while not text.utf8_at_end(source, at) do
        return when next >= last
        at = unicode.%(unit)s_end(source, at)
        return when text.offset(at) <> usize(boundaries[next])
        inc next
    end while
    return when next <> last
    next = first
    for piece in unicode.%(plural)s(source) do
        return when next >= last
        return when text.offset(piece.ends) <> usize(boundaries[next])
        inc next
    end for
    yes = next == last
end holds

public main: () -> (code: i32) =
    code = 1
    mut index: usize = 0
    while index < lenof ends do
        return when not holds(index)
        inc index
    end while
    code = 42
end main
""" % {"unit": unit, "plural": plural}).split("\n")
    return lines


BREAKS = (
    ("auxiliary/GraphemeBreakTest.txt", "grapheme", "graphemes"),
    ("auxiliary/WordBreakTest.txt", "word", "words"),
    ("auxiliary/SentenceBreakTest.txt", "sentence", "sentences"),
)


def render_all(database):
    """Each fixture's main.ldn, by path."""
    made = {
        "unicode-category": category_fixture(database),
        "unicode-properties": properties_fixture(database),
        "unicode-case-scalars": case_fixture(database),
        "unicode-case-title": title_fixture(database),
        "unicode-normalization-canonical":
            scalar_normalization_fixture(database, "canonical", 61),
        "unicode-normalization-compatible":
            scalar_normalization_fixture(database, "compatible", 61),
        "unicode-normalization-sequences": sequences_fixture(database),
    }
    for member, unit, plural in BREAKS:
        parts = break_parts(break_cases(database.members[member]))
        for number, cases in enumerate(parts, 1):
            name = "unicode-" + plural
            if len(parts) > 1:
                name += "-%d" % number
            made[name] = break_fixture(member, unit, plural, cases, number,
                                       len(parts))
    return {tables.FIXTURES / name / "main.ldn":
            "\n".join(lines).rstrip("\n") + "\n"
            for name, lines in made.items()}
